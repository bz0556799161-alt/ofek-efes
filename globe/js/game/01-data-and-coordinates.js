/* ============================================================================
   CELESTIAL — ECLIPTIC GEOMETRY (single source, per the coordinate-system
   review): the Milky Way/ecliptic plane's pole and its own (u,v) tangent
   basis, built exactly ONCE, purely from RA/Dec (RA=270°, Dec=66.560709°,
   J2000 mean-obliquity figure). Every consumer - the real 3D band
   (buildEclipticBand), the mini-map's ring (miniEclipticRing), and the
   map's "align to ecliptic" VIEW (updateMiniMap) - reads this one object
   instead of each re-deriving the pole/basis from the raw RA/Dec numbers
   independently (three separate copies of the same trig used to exist).
   This is pure CELESTIAL-frame geometry: it knows nothing about the
   structure's hour rotation or tilt - callers apply the structure's own
   orientation (getStructureQuaternion) on top of these directions
   themselves, which is the ECLIPTIC_GEOMETRY -> STRUCTURE ORIENTATION ->
   WORLD pipeline the review called for, never the reverse.
   ============================================================================ */
const ECLIPTIC_GEOMETRY = (function(){
  const poleRaDeg = 270.0, poleDecDeg = 66.560709;
  const poleRa = poleRaDeg*(Math.PI/180), poleDec = poleDecDeg*(Math.PI/180);
  // z negated to match the ASTRONOMICAL HANDEDNESS MIRROR applied to the raw
  // room data above (and to buildStars()/buildAsterismLines() below) - same
  // single sign flip, everywhere this RA/Dec->XYZ convention is used.
  const pole = new THREE.Vector3(Math.cos(poleDec)*Math.cos(poleRa), Math.sin(poleDec), -Math.cos(poleDec)*Math.sin(poleRa)).normalize();
  // any vector not parallel to `pole` seeds an orthonormal (u,v) basis
  // spanning the plane perpendicular to it (the plane itself)
  const seed = Math.abs(pole.y) < 0.9 ? new THREE.Vector3(0,1,0) : new THREE.Vector3(1,0,0);
  const u = new THREE.Vector3().crossVectors(seed, pole).normalize();
  const v = new THREE.Vector3().crossVectors(pole, u).normalize();
  // a point on the ecliptic great circle itself, parameterized by angle
  // theta (radians) around the pole, at ecliptic-latitude offset `lat`
  // (radians, 0 = exactly on the circle) - the one shared formula every
  // consumer below calls instead of repeating the cos/sin/add by hand.
  function pointAt(theta, lat=0){
    const c = u.clone().multiplyScalar(Math.cos(theta)).add(v.clone().multiplyScalar(Math.sin(theta)));
    if(lat===0) return c;
    return c.multiplyScalar(Math.cos(lat)).add(pole.clone().multiplyScalar(Math.sin(lat)));
  }
  return { pole, u, v, pointAt };
})();
