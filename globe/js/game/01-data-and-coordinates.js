/* ============================================================================
   ASTRONOMICAL HANDEDNESS MIRROR — the raw room/constellation boundary data
   (pts3d/centroid3d/pts2d) was generated with the standard star-chart/globe
   convention: x=cos(dec)cos(ra), y=sin(dec), z=cos(dec)sin(ra), which is the
   correct convention for a chart drawn as seen from OUTSIDE the celestial
   sphere. This structure is walked from INSIDE it, looking out/up at the
   sky, which is the opposite handedness - every room boundary, star and
   asterism line needs to be mirrored, consistently, the same way, or the
   constellations read backwards from how they'd actually look overhead.
   This is applied exactly ONCE, here, to the raw data itself (negating one
   axis - Z, matching the sign flip applied below to every live RA/Dec
   formula in buildStars()/buildAsterismLines()/ECLIPTIC_GEOMETRY), so every
   consumer (the real structure AND the mini-map, both of which read ROOMS/
   PASSAGES) automatically gets the same, single, correct geometry - never a
   per-room or per-consumer patch. Each room's pts3d/pts2d point ORDER is
   also reversed (pts2d stays otherwise untouched - it only has to keep the
   same index correspondence with pts3d for earcutTriangulate(), not carry
   its own mirrored values) so the polygon winding - and therefore every
   outward-facing wall/floor normal computed from consecutive edges - comes
   out correct after the reflection, instead of flipped inward.
   ============================================================================ */
(function applyAstronomicalMirror(){
  if(!window.SPHERE_ROOMS) return;
  window.SPHERE_ROOMS.forEach(room=>{
    if(room.centroid3d) room.centroid3d = [room.centroid3d[0], room.centroid3d[1], -room.centroid3d[2]];
    if(room.pts3d) room.pts3d = room.pts3d.map(p=>[p[0], p[1], -p[2]]).reverse();
    if(room.pts2d) room.pts2d = room.pts2d.slice().reverse();
  });
  if(window.SPHERE_PASSAGES){
    window.SPHERE_PASSAGES.forEach(p=>{
      if(p.mid3d) p.mid3d = [p.mid3d[0], p.mid3d[1], -p.mid3d[2]];
    });
  }
})();

